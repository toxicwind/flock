import glob, json, hashlib, hmac, time, uuid, zmq
conn_files = sorted(glob.glob("/tmp/tmp*.json"))
with open(conn_files[0]) as f:
    conn = json.load(f)
print(f"Kernel: {conn['ip']}:{conn['shell_port']} key={conn['key'][:8]}...")
ctx = zmq.Context()
shell = ctx.socket(zmq.DEALER)
shell.connect(f"{conn['transport']}://{conn['ip']}:{conn['shell_port']}")
key = conn["key"].encode()
header = json.dumps({"msg_id": str(uuid.uuid4()), "username": "kernel", "session": str(uuid.uuid4()), "msg_type": "execute_request", "version": "5.3", "date": time.strftime("%Y-%m-%dT%H:%M:%S%z")})
content = json.dumps({"code": "print('LIVE_TEST_OK', __import__('os').getpid())", "silent": False, "store_history": False})
msg_list = [header, json.dumps({}), json.dumps({}), content]
auth = hmac.new(key, digestmod=hashlib.sha256)
for m in msg_list: auth.update(m.encode())
sig = auth.hexdigest()
shell.send_multipart([b"<IDS|MSG>", sig.encode(), header.encode(), json.dumps({}).encode(), json.dumps({}).encode(), content.encode()])
parts = shell.recv_multipart()
idx = parts.index(b"<IDS|MSG>")
status = json.loads(parts[idx+5].decode())
print(f"Status: {status.get('status')}")
shell.close(); ctx.term()
